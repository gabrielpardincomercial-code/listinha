// Pre-compile normalized terms sorted by length descending so more specific phrases match first
const COMPILED_RULES: Array<{ normTerm: string; suggestion: SmartSuggestion }> = [];
for (const group of RAW_BR_DICTIONARY) {
  for (const term of group.terms) {
    COMPILED_RULES.push({
      normTerm: normalizeBr(term),
      suggestion: group.suggestion,
    });
  }
}
COMPILED_RULES.sort((a, b) => b.normTerm.length - a.normTerm.length);

export function detectSmartCategory(name: string): SmartSuggestion {
  const clean = normalizeBr(name);
  if (!clean) {
    return u('mercearia', 1, 'un');
  }

  const padded = ` ${clean} `;

  // 1st pass: exact word / phrase boundary match (prevents false partial matches)
  for (const rule of COMPILED_RULES) {
    if (padded.includes(` ${rule.normTerm} `)) {
      return rule.suggestion;
    }
  }

  // 2nd pass: prefix/substring match for plurals or diminutives (e.g., "misturinha", "cervejinha", "bananas")
  for (const rule of COMPILED_RULES) {
    if (rule.normTerm.length >= 4 && clean.includes(rule.normTerm)) {
      return rule.suggestion;
    }
  }

  return u('mercearia', 1, 'un');
}

export function formatQuantityDisplay(item: {
  quantityType: QuantityType;
  quantity: number;
  weightPreset?: WeightPreset;
  unitLabel: string;
  customQuantity?: string;
}): string {
  if (item.customQuantity && item.customQuantity.trim()) {
    return item.customQuantity;
  }

  if (item.quantityType === 'weight') {
    if (item.quantity >= 1000) {
      const kg = item.quantity / 1000;
      return `${kg % 1 === 0 ? kg : kg.toFixed(1)}kg`;
    }
    return `${item.quantity}g`;
  }

  return `${item.quantity} ${item.unitLabel || 'un'}`;
}
