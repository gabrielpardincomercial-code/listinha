export interface SmartSuggestion {
  category: string;
  quantityType: QuantityType;
  defaultQuantity: number;
  weightPreset?: WeightPreset;
  unitLabel: string;
}

const u = (category: string, defaultQuantity = 1, unitLabel = 'un'): SmartSuggestion => ({
  category,
  quantityType: 'unit',
  defaultQuantity,
  unitLabel,
});

const w = (
  category: string,
  grams: 100 | 500 | 1000 = 1000
): SmartSuggestion => ({
  category,
  quantityType: 'weight',
  defaultQuantity: grams,
  weightPreset: grams === 100 ? '100g' : grams === 500 ? '500g' : '1kg',
  unitLabel: grams >= 1000 ? 'kg' : 'g',
});

// Normalization helper: removes accents, punctuation, extra spaces (e.g. "Maçã!" -> "maca")
function normalizeBr(str: string): string {
  return str
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

